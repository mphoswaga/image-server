const {test,expect}=require('@playwright/test');
const {signInDisposableTeacher,expectNoPageOverflow}=require('./helpers');
test('assessment library pages and filters statuses without exposing every control',async({page},info)=>{
 await signInDisposableTeacher(page,'assessment-library');
 const assignments=Array.from({length:18},(_,i)=>({id:'library-assessment-'+i,title:i===9?'Understanding Data and Information':'Computing test '+i,type:'assessment',assessmentType:i%3?'test':'quiz',subject:'ICT',grade:'Grade 3',rosterId:i%2?'class-b':'class-a',roomCode:'ROOM'+i,submissions:20,totalMarks:50,createdAt:new Date(Date.UTC(2026,9,i+1)).toISOString(),delivery:{mode:'live',phase:'marking'},teacherMarked:i>=10,schoolSystemCaptured:i>=15,contentEditable:true,status:'published',marking:{state:i<10?'needs-marking':'marked',label:i<10?'Needs marking':'Marked',expected:25}}));
 await page.route('**/api/assignments',r=>r.fulfill({json:{assignments}}));
 await page.route('**/api/rosters',r=>r.fulfill({json:{rosters:[{id:'class-a',name:'Grade 3B1',count:25},{id:'class-b',name:'Grade 3B2',count:25}]}}));
 await page.locator('#assignmentsBtn').click();
 await expect(page.locator('[data-assignment-status-card]:visible')).toHaveCount(7);
 await expect(page.locator('#assessmentSavedCount')).toHaveText('18 saved');
 await expect(page.locator('#assignmentFilterStatus')).toContainText('1–7 of 10');
 const first=page.locator('[data-assignment-status-card]:visible').first();
 await expect(first.locator('.assessment-management')).toBeHidden();
 await expect(first.locator('.a-toggle-btn')).toHaveText('Mark work');
 await expectNoPageOverflow(page);
 await page.screenshot({path:'/tmp/assessment-library-'+info.project.name+'.png',fullPage:true});
 await page.locator('#assignmentPagination').getByRole('button',{name:'Next →',exact:true}).click();
 await expect(page.locator('[data-assignment-status-card]:visible')).toHaveCount(3);
 await page.locator('#assignmentClassFilter').selectOption('class-a');
 await expect(page.locator('#assignmentFilterStatus')).toContainText('1–5 of 5');
 await page.locator('#assignmentTypeFilter').selectOption('quiz');
 await expect(page.locator('[data-assignment-status-card]:visible')).toHaveCount(2);
 await page.locator('#assignmentClassFilter').selectOption('');await page.locator('#assignmentTypeFilter').selectOption('');
 await page.locator('#assignmentSort').selectOption('oldest');
 await expect(first).toContainText('Computing test 0');
 await page.getByRole('searchbox',{name:'Find a test'}).fill('Information');
 await expect(page.locator('[data-assignment-status-card]:visible')).toHaveCount(1);
 await page.evaluate(()=>{window.copiedRoom='';copyLink=text=>window.copiedRoom=text;});
 await first.getByRole('button',{name:'Copy room code ROOM9',exact:true}).click();
 expect(await page.evaluate(()=>copiedRoom)).toBe('ROOM9');
 await first.locator('[data-assessment-manage]').click();
 await expect(first.getByRole('button',{name:'Attendance',exact:true})).toBeVisible();
 await expect(first.locator('.a-captured-toggle')).toBeDisabled();
 await expectNoPageOverflow(page);
 await first.locator('[data-assessment-manage]').click();
 await expect(first.locator('.a-marked-toggle')).toBeHidden();
 await page.getByRole('searchbox',{name:'Find a test'}).fill('');
 await page.locator('[data-assignment-status="marked"]').click();
 await expect(page.locator('[data-assignment-status-card]:visible')).toHaveCount(5);
 await page.locator('[data-assignment-status="captured"]').click();
 await expect(page.locator('[data-assignment-status-card]:visible')).toHaveCount(3);
 await page.getByRole('searchbox',{name:'Find a test'}).fill('no matching name');
 await expect(page.locator('#assignmentFilterStatus')).toContainText('No assessments match');
 await expect(page.locator('.assessment-column-head')).toBeHidden();
});
