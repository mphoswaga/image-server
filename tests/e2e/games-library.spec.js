const {test,expect}=require('@playwright/test');
const {signInDisposableTeacher,expectNoPageOverflow}=require('./helpers');
test('games library filters, paginates, shares and locates off-page content from the chooser',async({page},info)=>{
 await signInDisposableTeacher(page,'game-library');
 const games=Array.from({length:16},(_,i)=>({id:'content-'+i,lessonTitle:i===2?'Nguyễn Algorithms':'Computing content '+i,topic:'Computing',subject:'ICT',grade:'Grade 3',questionCount:6,plays:i,mode:i%5===0?'colonyquest':i%5===1?'fishquest':'arcade',rosterIds:[i%2?'class-b':'class-a'],roomCode:'GAME'+i,createdAt:new Date(Date.UTC(2026,9,i+1)).toISOString(),cutoffAt:i%2?'2020-01-01T00:00:00Z':'2099-01-01T00:00:00Z'}));
 await page.route('**/api/games',route=>route.fulfill({json:{games}}));
 await page.route('**/api/rosters',route=>route.fulfill({json:{rosters:[{id:'class-a',name:'Grade 3A',count:25},{id:'class-b',name:'Grade 3B',count:26}]}}));
 await page.route('**/api/games/moonquest/library',route=>route.fulfill({json:{games:[{id:'diagram',title:'Diagram lesson',questions:4,subject:'ICT',grade:'Grade 3',createdAt:'2026-11-01T00:00:00Z'}],sessions:[]}}));
 await page.locator('#gamesBtn').click();
 await expect(page.locator('#gamesSavedCount')).toHaveText('17 question sets');
 await expect(page.locator('#gamesList>.game-card')).toHaveCount(7);
 await expectNoPageOverflow(page);
 await page.screenshot({path:'/tmp/games-library-'+info.project.name+'.png',fullPage:true});
 await page.locator('#gamesPagination').getByRole('button',{name:'Next →',exact:true}).click();
 await expect(page.locator('#gamesLibraryStatus')).toContainText('8–14 of 17');
 await page.locator('#gamesStatusFilter').selectOption('whole');
 await expect(page.locator('#gamesLibraryStatus')).toContainText('1–4 of 4');
 await expect(page.locator('#gamesList>.game-card').first().locator('.game-library-plays')).toHaveText('—');
 await page.locator('#gamesStatusFilter').selectOption('diagram');
 await expect(page.locator('#gamesList>.game-card')).toHaveCount(1);
 await expect(page.locator('.game-library-row')).toContainText('Diagram content');
 await page.locator('#gamesStatusFilter').selectOption('all');
 await page.getByRole('searchbox',{name:'Search game content'}).fill('nguyen');
 await expect(page.locator('#gamesList>.game-card')).toHaveCount(1);
 await expect(page.locator('.game-library-row')).toContainText('Nguyễn Algorithms');
 await page.locator('#gamesClassFilter').selectOption('class-b');
 await expect(page.locator('#gamesList')).toContainText('No content matches');
 await page.locator('#gamesClassFilter').selectOption('all');await page.locator('#gamesSearch').fill('');
 await page.getByRole('button',{name:'Browse games',exact:true}).click();
 const code=page.locator('.games-option').filter({has:page.getByRole('heading',{name:'CodeQuest',exact:true})});
 await code.getByRole('combobox').selectOption('content-0');await code.locator('summary').click();
 await expect(code.getByRole('link',{name:'Treasure duels · learner devices →',exact:true})).toHaveAttribute('href','/codequest.html?game=content-0');
 await code.getByRole('button',{name:'Review assigned classes',exact:true}).click();
 const card=page.locator('[data-game-content="content-0"]');
 await expect(card).toBeVisible();await expect(card.locator('.gc-class-row')).toBeVisible();
 await card.getByRole('button',{name:'Cancel',exact:true}).click();
 await card.getByRole('button',{name:'Share with learners',exact:true}).click();
 await expect(card.getByRole('button',{name:'Copy learner link',exact:true})).toBeVisible();
 await expect(card.locator('.game-link input')).toHaveValue(/play\/content-0\?activity=colonyquest-live$/);
 await card.locator('.game-manage-toggle').click();await expect(card.locator('.game-management')).toBeHidden();
 await expectNoPageOverflow(page);
 await page.getByRole('button',{name:'Create lesson content',exact:true}).click();
 await expect(page.locator('#fromPptxDetails')).toHaveAttribute('open','');
});
