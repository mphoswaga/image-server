const {test,expect}=require('@playwright/test');
const {signInDisposableTeacher,expectNoPageOverflow}=require('./helpers');
test('lesson library filters, sorts, pages, opens action menus and archives',async({page},info)=>{
 await signInDisposableTeacher(page,'library');
 const lessons=Array.from({length:16},(_,i)=>({id:'library-'+i,topic:i===15?'3 Computational Thinking':i===14?'2 Nguyễn Data':'Lesson '+i,subject:i%3?'ICT':'Science',grade:i%2?'Grade 2':'Grade 3',stage:i%3?'assigned':'plan',updatedAt:new Date(Date.UTC(2026,10,i+1,10)).toISOString(),hasPlan:true,deckCount:1,resourceCount:1,assignmentCount:1,gameCount:1}));
 await page.route('**/api/lesson-workspaces',r=>r.request().method()==='GET'?r.fulfill({json:{lessons}}):r.continue());
 await page.locator('#lessonsBtn').click();
 await expect(page.locator('.library-row')).toHaveCount(7);
 await expect(page.locator('#lessonsSavedCount')).toHaveText('16 saved');
 await expect(page.locator('.library-row').first()).toContainText('Computational Thinking');
 await expectNoPageOverflow(page);
 await page.screenshot({path:'/tmp/lesson-library-'+info.project.name+'.png',fullPage:true});
 await page.getByRole('button',{name:'Next →',exact:true}).click();
 await expect(page.locator('#lessonsPagination')).toContainText('Showing 8–14 of 16');
 await page.locator('#lessonsGrade').selectOption('Grade 2');
 await expect(page.locator('#lessonsPagination')).toContainText('Showing 1–7 of 8');
 await page.locator('#lessonsSubject').selectOption('Science');
 await expect(page.locator('.library-row')).toHaveCount(3);
 await page.locator('#lessonsGrade').selectOption('');await page.locator('#lessonsSubject').selectOption('');
 await page.getByRole('searchbox',{name:'Search lessons'}).fill('nguyen');
 await expect(page.locator('.library-row')).toHaveCount(1);
 await page.getByRole('searchbox',{name:'Search lessons'}).fill('no match at all');
 await expect(page.locator('#lessonsList')).toContainText('No lessons match');
 await page.getByRole('searchbox',{name:'Search lessons'}).fill('');
 await page.locator('#lessonsSort').selectOption('oldest');
 await expect(page.locator('.library-row').first()).toContainText('Lesson 0');
 const firstMenu=page.locator('.library-action-menu').first();
 await expect(firstMenu.getByRole('button',{name:'Archive lesson',exact:true})).toBeHidden();
 await firstMenu.locator('summary').click();
 await expect(firstMenu.getByRole('button',{name:'Rebuild from learning objectives',exact:true})).toBeVisible();
 await page.locator('.library-action-menu').nth(1).locator('summary').focus();
 await page.keyboard.press('Enter');
 await expect(firstMenu).not.toHaveAttribute('open','');
 await page.keyboard.press('Escape');
 await expect(page.locator('.library-action-menu[open]')).toHaveCount(0);
 await firstMenu.locator('summary').click();
 await firstMenu.getByRole('button',{name:'Games',exact:true}).click();
 await expect(page.locator('#gamesPanel')).toBeVisible();
 await page.locator('#lessonsBtn').click();
 await page.route('**/api/lesson-workspaces/library-0',async route=>{expect(route.request().method()).toBe('PATCH');expect(route.request().postDataJSON()).toEqual({archived:true});await route.fulfill({json:{ok:true}});});
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('.library-action-menu').first().locator('summary').click();
 await page.locator('.library-action-menu').first().getByRole('button',{name:'Archive lesson',exact:true}).click();
 await expect(page.locator('#lessonsSavedCount')).toHaveText('15 saved');
 await page.locator('#newLessonBtn').click();
 await expect(page.locator('#modeSelect')).toBeVisible();
});
