const {test,expect}=require('@playwright/test');
const {signInDisposableTeacher}=require('./helpers');
test('teacher previews learner dashboard without creating a learner session',async({page})=>{
 await signInDisposableTeacher(page,'preview');
 const r=await page.request.post('/api/roster',{data:{name:'Preview class',rows:[{ID:'PREVIEW01',Name:'Preview Learner'}],idCol:'ID',nameCol:'Name'}});expect(r.ok()).toBeTruthy();
 expect((await page.request.get('/api/student-profiles/UNKNOWN/preview/me')).status()).toBe(404);
 await page.locator('#rostersBtn').click();
 await page.getByRole('button',{name:'Student access',exact:true}).click();
 const row=page.locator('.pin-student-row').first();
 await expect(row.getByRole('link',{name:'View as student'})).toBeVisible();
 await expect(row.locator('.student-gender-value')).toBeHidden();
 await row.locator('summary').click();
 await expect(row.locator('.student-gender-value')).toBeVisible();
 await row.locator('summary').click();
 await page.screenshot({path:'/tmp/roster-clean-preview.png',fullPage:true});
 const popupPromise=page.waitForEvent('popup');
 await row.getByRole('link',{name:'View as student'}).click();
 const popup=await popupPromise;
 await expect(popup.locator('#previewBanner')).toContainText('Viewing as Preview Learner');
 await popup.close();
 await page.goto('/start?previewStudent=PREVIEW01');
 await expect(page.locator('#previewBanner')).toContainText('Viewing as Preview Learner');
 await expect(page.locator('#dashboard')).toBeVisible();
 await expect(page.locator('#todoList')).not.toContainText('Finding your activities');
 await page.locator('#roomCode').fill('ABCDEF');
 let joins=0;page.on('request',r=>{if(r.url().includes('/join-room'))joins++;});
 await page.locator('#joinBtn').click();expect(joins).toBe(0);
 expect((await page.request.get('/api/student/me')).status()).not.toBe(200);
 await page.route('**/api/student-profiles/PREVIEW01/preview/activities',route=>route.fulfill({json:{live:[],todo:[{id:'preview-task',kind:'assignment',title:'Preview task',code:'TASK01'}]}}));
 await page.route('**/assignment/preview-task',route=>route.fulfill({contentType:'text/html',body:'<h1>Task preview opened</h1>'}));
 await page.reload();
 await expect(page.getByRole('button',{name:'Open task'})).toBeVisible();
 await page.screenshot({path:'/tmp/student-dashboard-updated.png',fullPage:true});
 await page.getByRole('button',{name:'Open task'}).click();
 await expect(page).toHaveURL(/assignment\/preview-task/);
 await signInDisposableTeacher(page,'other');
 expect((await page.request.get('/api/student-profiles/PREVIEW01/preview/me')).status()).toBe(404);
});
